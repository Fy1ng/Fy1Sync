/**
 * Bundle the server into a single ESM file.
 *
 * `npm start` then runs `node dist/server/index.mjs` with no TypeScript loader, no
 * `node_modules` resolution and nothing to install. The server has no runtime dependencies
 * — everything it uses is in Node core — so the bundle is self-contained by construction,
 * and `external` staying empty is what keeps it that way.
 */

import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import { readFile } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'))

const result = await build({
  entryPoints: [fileURLToPath(new URL('server/index.ts', root))],
  outfile: fileURLToPath(new URL('dist/server/index.mjs', root)),
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'esm',
  // The client bundle is minified by Vite; the server is not, because a readable stack
  // trace from a local tool is worth more than the few kilobytes.
  minify: false,
  sourcemap: true,
  treeShaking: true,
  logLevel: 'warning',
  metafile: true,
  define: { 'process.env.STREAM_SYNC_VERSION': JSON.stringify(pkg.version) },
  banner: {
    js: [
      `// Stream Syncer ${pkg.version} — bundled server. Generated by scripts/build-server.mjs.`,
      '// Run with: node dist/server/index.mjs',
    ].join('\n'),
  },
})

const outputs = Object.entries(result.metafile.outputs).filter(([file]) => file.endsWith('.mjs'))
for (const [file, meta] of outputs) {
  process.stdout.write(`  ${file}  ${(meta.bytes / 1024).toFixed(1)} kB\n`)
}

const imports = new Set()
for (const meta of Object.values(result.metafile.outputs)) {
  for (const entry of meta.imports ?? []) {
    if (entry.external) imports.add(entry.path)
  }
}
const nonCore = [...imports].filter((name) => !name.startsWith('node:'))
if (nonCore.length > 0) {
  // A bare import would make `node dist/server/index.mjs` fail on a machine without an
  // `npm install`, which defeats the point of the bundle.
  process.stderr.write(`服务端产物包含外部依赖：${nonCore.join(', ')}\n`)
  process.exitCode = 1
}
