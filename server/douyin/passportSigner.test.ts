function referenceRandom(): () => number {
  let a = 20260927
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = Math.imul(a ^ (a >>> 15),a | 1)
    t = (t + Math.imul(t ^ (t >>> 7),t | 61)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

// Independent Apache-2.0 decode model: DTK 3c045e11, not the signer under test.
function decodeFrame(signature: string) {
  const alphabet = 'Dkdpgh2ZmsQB80/MfvV36XI1R45-WUAlEixNLwoqYTOPuzKFjJnry79HbGcaStCe'
  const standard = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/'
  const wire = Buffer.from(signature.replace(/[A-Za-z0-9+/-]/g, char => standard[alphabet.indexOf(char)]!), 'base64')
  const decrypt = (key: number[], data: Uint8Array): Buffer => {
    const box = Array.from({length:256},(_,i)=>255-i)
    let j = 0
    for (let i=0;i<256;i++) { j=(j*box[i]!+j+key[i%key.length]!)%256; [box[i],box[j]]=[box[j]!,box[i]!] }
    let i=0; j=0
    return Buffer.from(data.map(byte=>{ i=(i+1)%256; j=(j+box[i]!)%256; [box[i],box[j]]=[box[j]!,box[i]!]; return byte^box[(box[i]!+box[j]!)%256]! }))
  }
  const plain = decrypt([211],wire.subarray(4)), version = plain.subarray(0,8), frame = plain.subarray(8), raw: number[] = []
  for(let at=0;at<frame.length;at+=4) {
    const group=frame.subarray(at,at+4)
    if(group.length<4) {raw.push(...group);continue}
    for(const [index,mask,data] of [[0,145,110],[1,66,189],[2,44,211]]) raw.push((group[index!]!&data!)|(group[3]!&mask!))
  }
  const order = [34,44,56,61,73,29,70,45,35,49,38,66,51,68,28,48,64,47,30,71,26,55,31,69,59,40,62,63,27,72,41,74,57,52,42,39,33,67,53,43,65,46,36,24,60,32,79,80,84,85]
  const fields = Object.fromEntries(order.map((id,index)=>[id,raw[index]!])) as Record<number,number>
  const end=order.length+(fields[79]!|(fields[80]!<<8))+(fields[84]!|(fields[85]!<<8))
  const checksum=[...version,...order.map(id=>fields[id]!)].reduce((sum,byte)=>sum^byte,0)
  return {fields,checksumValid:raw[end]===checksum,decrypt}
}

describe('Douyin passport signing', () => {
  it('retains pinned dhzx reference outputs for the unaffected host profiles', () => {
    const random = referenceRandom()
    const hosts = ['www.douyin.com','live.douyin.com','creator.douyin.com','login.douyin.com']
    const queries = ['device_platform=webapp&aid=6383','a=%E4%B8%AD&b=','']
    const actual = queries.flatMap((query,i) => hosts.map(host => signDouyinPassportQuery(query,i === 1 ? 'x=1' : '',profile.ua,host,{ now:() => NOW,random })))
    expect(actual.filter((_,index)=>index%4!==3)).toEqual(VECTORS.filter((_,index)=>index%4!==3))
  })

  it('matches the independent native login reference after correcting nr flags', () => {
    const r = nativeReference
    const signature = signDouyinPassportQuery(r.query,r.body,r.userAgent,'login.douyin.com',{now:()=>r.now,random:()=>r.random})
    expect(signature).toBe(r.signature)
    const decoded=decodeFrame(signature)
    expect(decoded.fields[38]).toBe(33)
    expect(decoded.fields[44]).toBe(14)
    expect(decoded.checksumValid).toBe(true)
  })

  it('checks real browser frames independently of the synthetic upstream vectors', () => {
    for(const sample of browserSamples) {
      const decoded=decodeFrame(sample.a_bogus)
      expect(decoded.checksumValid).toBe(true)
      expect(decoded.fields[38]).toBe(33)
      const digest=(text:string)=>createHash('sm3').update(createHash('sm3').update(text+'dhzx').digest()).digest()
      const q=digest(sample.query), b=digest(sample.body)
      expect([decoded.fields[48],decoded.fields[49]]).toEqual([q[9],q[18]])
      expect([decoded.fields[52],decoded.fields[53]]).toEqual([b[10],b[19]])
    }
  })

  it('binds exact body, query, UA and host without retaining shared cipher state', () => {
    const sign = (query = 'aid=6383',body = 'token=example%2Btoken',ua = profile.ua,host = 'login.douyin.com') => signDouyinPassportQuery(query,body,ua,host,{ now:() => NOW,random:referenceRandom() })
    const initial = sign()
    expect(sign()).toBe(initial)
    expect(sign('aid=6383','token=example+token')).not.toBe(initial)
    expect(sign('aid=6383','')).not.toBe(initial)
    expect(sign('aid=6383&fp=other')).not.toBe(initial)
    expect(sign('aid=6383','token=example%2Btoken',profile.ua.replace('155.0.0.0','156.0.0.0'))).not.toBe(initial)
    expect(sign('aid=6383','token=example%2Btoken',profile.ua,'www.douyin.com')).not.toBe(initial)
  })

  it('rejects a previously signed query, invalid entropy and non-platform hosts', () => {
    for (const query of ['a=中文','a=1&a_bogus=old','a=\n']) expect(() => signDouyinPassportQuery(query,'',profile.ua,'login.douyin.com')).toThrow()
    expect(() => signDouyinPassportQuery('a=1','',profile.ua,'attacker.invalid')).toThrow()
    for (const random of [() => NaN,() => -0.1,() => 1]) expect(() => signDouyinPassportQuery('a=1','',profile.ua,'login.douyin.com',{ now:() => NOW,random })).toThrow()
    expect(() => signDouyinPassportQuery('a=1','',profile.ua,'login.douyin.com',{ now:() => 1,random:Math.random })).toThrow()
  })

  it('generates one reusable identifier with the public SDK uppercase variant shape', () => {
    const values = Array.from({ length:16 },() => generateDouyinVerifyFp(NOW))
    const time = NOW.toString(36)
    for (const value of values) expect(value).toMatch(new RegExp(`^verify_${time}_[0-9A-Za-z]{8}_[0-9A-Za-z]{4}_4[0-9A-Za-z]{3}_[89AB][0-9A-Za-z]{3}_[0-9A-Za-z]{12}$`))
    expect(new Set(values).size).toBe(values.length)
    expect(generateDouyinVerifyFp(0)).toMatch(/^verify_0_/)
    expect(() => generateDouyinVerifyFp(-1)).toThrow()
  })

  it('matches BMP UTF8/XOR5 vectors and skips surrogate units as the public SDK does', () => {
    expect(encodeDouyinPassport('123456')).toBe('343736313033')
    expect(encodeDouyinPassport('中文')).toBe('e1bda8e39382')
    expect(encodeDouyinPassport('\x00\x05\n')).toBe('50f')
    expect(encodeDouyinPassport('a\ud800\udfff😀b')).toBe(encodeDouyinPassport('ab'))
    expect(encodeDouyinPassport('')).toBe('')
  })

  it('sorts raw signable fields and includes body before hashing', () => {
    const query = { b:'x y',a:'1',sign:'old',qs:'old',msToken:'unrelated',a_bogus:'old' }
    const body = { z:'1',a:'raw+text' }
    const signed = signDouyinPassportParams(query,body)
    // Independent Python hashlib reference, not a snapshot generated by this implementation.
    expect(signed).toEqual({ sign:'028293bd637ad2f411f3b5fc1ddf126833c2af22a9ff66ebfd8bf4e12dac6f12',qs:'642967' })
    expect(signDouyinPassportParams({ a:'1',b:'x y' },{ a:'raw+text',z:'1' })).toEqual(signed)
    expect(signDouyinPassportParams(query,{ ...body,z:'2' }).sign).not.toBe(signed.sign)
    expect(query.sign).toBe('old')
    const many = Object.fromEntries(Array.from({ length:12 },(_,i) => [`k${String(i).padStart(2,'0')}`,String(i)]))
    expect(signDouyinPassportParams(many,{})).toEqual(signDouyinPassportParams({ ...many,k10:'excluded',k11:'excluded' },{}))
    expect(signDouyinPassportParams(many,{}).sign).not.toBe(signDouyinPassportParams({ ...many,k09:'signed' },{}).sign)
    expect(signDouyinPassportParams({},{}).sign).toBe(createHash('sha256').update(`&&app_key=${APP_KEY}`).digest('hex'))
  })

  it('uses UTC noon and interoperates with an independent standard HKDF implementation', () => {
    const path = '/passport/web/check_qrconnect/'
    const expected = { header:'fafbd8273dcbb0671eaffc2e89162627e85dd75a82860a43011823806f5cce2b',ts:'1794484800' }
    expect(douyinPassportAidSignature(path,6383,APP_KEY,Date.parse('2026-11-12T00:01:00Z'))).toEqual(expected)
    expect(douyinPassportAidSignature(path,6383,APP_KEY,Date.parse('2026-11-12T23:59:00Z'))).toEqual(expected)
    const key = hkdfSync('sha256',APP_KEY,expected.ts,'',32)
    expect(createHmac('sha256',Buffer.from(key)).update(`aid=6383&path=${path}&ts=${expected.ts}`).digest('hex')).toBe(expected.header)
    expect(douyinPassportAidSignature(path,6383,APP_KEY,Date.parse('2026-11-13T00:00:00Z'))).not.toEqual(expected)
    expect(() => douyinPassportAidSignature(`${path}?x=1`,6383,APP_KEY,NOW)).toThrow()
  })
})
