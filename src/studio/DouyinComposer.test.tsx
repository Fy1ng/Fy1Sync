import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { apiClient } from '../app/apiClient'
import { DouyinComposer } from './DouyinComposer'
import type { ApiResult } from '../app/apiClient'
import type { DouyinMessageOutcome } from '../core/douyinMessage'
import { DOUYIN_LOGIN_CHANGED_EVENT } from '../core/douyinMessage'

const authenticated = { loggedIn:true, canSend:true, uid:'12345', nickname:'测试账号', message:'仅发送普通文字弹幕.' }
beforeEach(() => {
  vi.spyOn(apiClient,'getDouyinSendState').mockResolvedValue({ ok:true, value:authenticated })
  vi.spyOn(apiClient,'sendDouyinMessage').mockResolvedValue({ ok:true, value:{ status:'accepted', message:'平台已受理, 尚未确认房间显示.', nextAllowedAt:null } })
})
afterEach(() => { cleanup(); vi.restoreAllMocks() })
async function mount() {
  const onLogin = vi.fn()
  const view = render(<DouyinComposer room="douyin:100" connected onLogin={onLogin} />)
  const input = screen.getByRole('textbox',{ name:'抖音弹幕内容' })
  await waitFor(() => expect(input).toBeEnabled())
  return { ...view, input, onLogin, send:screen.getByRole('button',{ name:'发送' }) }
}
describe('explicit Douyin message composer', () => {
  it('offers completion of stored-key authentication for a verified account with older Cookie-only login',async()=>{
    const onLogin=vi.fn()
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{...authenticated,canSend:false,loginState:'authenticated',
      message:'请重新登录以保存发送认证.',detail:{code:'douyin-signing-material-missing'}}})
    render(<DouyinComposer room="douyin:100" connected onLogin={onLogin}/>)
    await screen.findByText('请重新登录以保存发送认证.')
    expect(screen.getByRole('textbox')).toBeDisabled()
    fireEvent.click(screen.getByRole('button',{name:'重新登录抖音'}))
    expect(onLogin).toHaveBeenCalledOnce()
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
  })
  it('keeps verified login distinct from send readiness and does not offer relogin as the missing-protocol remedy', async () => {
    const onLogin = vi.fn()
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{ ...authenticated,loginState:'authenticated',canSend:false,message:'本地发送认证尚未完成.' }})
    render(<DouyinComposer room="douyin:100" connected onLogin={onLogin} />)
    await screen.findByText('当前抖音账号：测试账号')
    const input = screen.getByRole('textbox',{name:'抖音弹幕内容'})
    expect(input).toBeDisabled()
    expect(screen.getByRole('button',{name:'发送'})).toBeDisabled()
    expect(screen.queryByRole('button',{name:'重新登录抖音'})).toBeNull()
    expect(screen.queryByRole('button',{name:'登录抖音'})).toBeNull()
    fireEvent.keyDown(input,{key:'Enter'})
    fireEvent.click(screen.getByRole('button',{name:'刷新账号'}))
    await waitFor(() => expect(apiClient.getDouyinSendState).toHaveBeenCalledTimes(2))
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
    expect(onLogin).not.toHaveBeenCalled()
  })
  it('offers account settings without suggesting repeated relogin when production signing is unavailable', async () => {
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{loggedIn:false,canSend:false,loginState:'expired',
      message:'本地发送认证尚未完成.',detail:{code:'douyin-http-signing-unavailable',platformCode:20003}}})
    const onLogin=vi.fn()
    render(<DouyinComposer room="douyin:100" connected onLogin={onLogin} />)
    await screen.findByText('本地发送认证尚未完成.')
    expect(screen.getByRole('button',{name:'发送'})).toBeDisabled()
    expect(screen.queryByRole('button',{name:'重新登录抖音'})).toBeNull()
    fireEvent.click(screen.getByRole('button',{name:'抖音账号设置'}))
    expect(onLogin).toHaveBeenCalledOnce()
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
  })
  it('coalesces automatic focus reads while an explicit refresh still reaches the current identity', async () => {
    const { input } = await mount()
    for (let index=0; index<8; index++) { fireEvent(window,new Event('focus')); fireEvent.focus(input) }
    expect(apiClient.getDouyinSendState).toHaveBeenCalledOnce()
    fireEvent.click(screen.getByRole('button',{name:'刷新账号'}))
    await waitFor(() => expect(apiClient.getDouyinSendState).toHaveBeenCalledTimes(2))
    expect(apiClient.getDouyinSendState).toHaveBeenLastCalledWith(true)
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
  })
  it('preserves a draft through an unknown identity read and recovery of the same account', async () => {
    const { input } = await mount()
    fireEvent.change(input,{target:{value:'仍在编辑的草稿'}})
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{loggedIn:false,canSend:false,loginState:'unavailable',message:'网络暂时无法核对账号.'}})
    fireEvent.click(screen.getByRole('button',{name:'刷新账号'}))
    await screen.findByText('网络暂时无法核对账号.')
    expect(input).toBeDisabled()
    expect(input).toHaveValue('仍在编辑的草稿')
    expect(screen.queryByRole('button',{name:'重新登录抖音'})).toBeNull()
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:authenticated})
    fireEvent.click(screen.getByRole('button',{name:'刷新账号'}))
    await waitFor(() => expect(input).toBeEnabled())
    expect(input).toHaveValue('仍在编辑的草稿')
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
  })
  it('keeps an expired account draft until a newly verified different account establishes a transition', async () => {
    const { input } = await mount()
    fireEvent.change(input,{target:{value:'等待原账号恢复'}})
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{loggedIn:false,canSend:false,loginState:'expired',message:'抖音会话已失效.'}})
    fireEvent.click(screen.getByRole('button',{name:'刷新账号'}))
    await screen.findByText('抖音会话已失效.')
    expect(input).toBeDisabled()
    expect(input).toHaveValue('等待原账号恢复')
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{...authenticated,uid:'98765'}})
    fireEvent.click(screen.getByRole('button',{name:'刷新账号'}))
    await waitFor(() => expect(input).toBeEnabled())
    expect(input).toHaveValue('')
  })
  it('preserves a failed API response while leaving accepted receipts plain', async () => {
    vi.mocked(apiClient.sendDouyinMessage).mockResolvedValue({ ok: false, code: 'SEND_HTTP_503', message: '测试发送失败', detail: { status: 503, traceId: 'douyin-send', cookie: 'private-cookie' } })
    const { input, send } = await mount()
    fireEvent.change(input, { target: { value: '本地测试草稿' } })
    fireEvent.click(send)
    fireEvent.click(await screen.findByRole('button', { name: '查看原始错误' }))
    const details = screen.getByRole('region', { name: '原始错误信息' })
    expect(JSON.parse(details.querySelector('code')!.textContent!)).toMatchObject({ code: 'SEND_HTTP_503', detail: { traceId: 'douyin-send', status: 503, cookie: '[redacted]' } })
    expect(details.textContent).not.toContain('本地测试草稿')
    vi.mocked(apiClient.sendDouyinMessage).mockResolvedValue({ ok: true, value: { status: 'accepted', message: '测试已受理', nextAllowedAt: null } })
    fireEvent.click(send)
    await screen.findByText('测试已受理')
    expect(screen.queryByRole('button', { name: '查看原始错误' })).toBeNull()
    expect(input).toHaveValue('')
  })
  it('automatically refreshes an expired account only after the completed login event',async()=>{
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{loggedIn:false,canSend:false,loginState:'expired',message:'抖音会话已失效.'}})
    render(<DouyinComposer room="douyin:100" connected onLogin={()=>{}}/>)
    await screen.findByText('抖音会话已失效.')
    expect(screen.getByRole('textbox')).toBeDisabled()
    expect(screen.getByRole('button',{name:'重新登录抖音'})).toBeInTheDocument()
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:authenticated})
    fireEvent(window,new Event(DOUYIN_LOGIN_CHANGED_EVENT))
    await waitFor(()=>expect(screen.getByRole('textbox')).toBeEnabled())
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
  })
  it('offers a refresh rather than a relogin when identity checking is unavailable',async()=>{
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ok:true,value:{loggedIn:false,canSend:false,loginState:'unavailable',message:'网络暂时无法核对账号.'}})
    render(<DouyinComposer room="douyin:100" connected onLogin={()=>{}}/>)
    await screen.findByText('网络暂时无法核对账号.')
    expect(screen.queryByRole('button',{name:'登录抖音'})).toBeNull()
    expect(screen.getByRole('button',{name:'刷新账号'})).toBeInTheDocument()
  })
  it('sends only on an explicit submit using the verified Douyin identity', async () => {
    const { input, send } = await mount()
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
    expect(send).toBeDisabled()
    fireEvent.change(input,{ target:{ value:' 测试 😀 ' } })
    fireEvent.click(send)
    await waitFor(() => expect(apiClient.sendDouyinMessage).toHaveBeenCalledExactlyOnceWith({ room:'douyin:100', expectedUid:'12345', text:'测试 😀' }))
    await waitFor(() => expect(input).toHaveValue(''))
    expect(screen.getByRole('status')).toHaveTextContent('尚未确认房间显示')
  })
  it('opens the account settings and keeps sending disabled when logged out', async () => {
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ ok:true, value:{ loggedIn:false, canSend:false, message:'请先登录抖音.' } })
    const onLogin = vi.fn()
    render(<DouyinComposer room="douyin:100" connected onLogin={onLogin} />)
    await screen.findByText('请先登录抖音.')
    expect(screen.getByRole('textbox')).toBeDisabled()
    expect(screen.queryByRole('button', { name: '查看原始错误' })).toBeNull()
    fireEvent.click(screen.getByRole('button',{ name:'登录抖音' }))
    expect(onLogin).toHaveBeenCalledOnce()
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
  })
  it('does not send while composing Chinese text or when text exceeds the local limit', async () => {
    const { input, send } = await mount()
    fireEvent.change(input,{ target:{ value:'测试' } }); fireEvent.compositionStart(input)
    fireEvent.keyDown(input,{ key:'Enter',code:'Enter' })
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
    fireEvent.compositionEnd(input)
    fireEvent.change(input,{ target:{ value:'长'.repeat(51) } })
    expect(send).toBeDisabled()
    expect(screen.getByText('请输入不超过 50 字的单行弹幕')).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: '查看原始错误' })).toBeNull()
    fireEvent.keyDown(input,{ key:'Enter',code:'Enter' })
    expect(apiClient.sendDouyinMessage).not.toHaveBeenCalled()
  })
  it('prevents two synchronous sends and preserves a newer draft while awaiting the receipt', async () => {
    let resolve!: (result:ApiResult<DouyinMessageOutcome>) => void
    vi.mocked(apiClient.sendDouyinMessage).mockReturnValue(new Promise(done => { resolve = done }))
    const { input, send } = await mount()
    fireEvent.change(input,{ target:{ value:'第一条' } }); fireEvent.click(send); fireEvent.keyDown(input,{ key:'Enter' })
    expect(apiClient.sendDouyinMessage).toHaveBeenCalledOnce()
    fireEvent.change(input,{ target:{ value:'新草稿' } })
    await act(async () => resolve({ ok:true, value:{ status:'accepted',message:'已受理',nextAllowedAt:null } }))
    expect(input).toHaveValue('新草稿')
  })
  it('preserves an uncertain draft, displays the result and never retries automatically', async () => {
    vi.mocked(apiClient.sendDouyinMessage).mockResolvedValue({ ok:true, value:{ status:'waiting-user',message:'结果无法确认, 不会自动重发.',nextAllowedAt:Date.now()+5000 } })
    const { input, send } = await mount()
    fireEvent.change(input,{ target:{ value:'保留草稿' } }); fireEvent.click(send)
    await screen.findByText('结果无法确认, 不会自动重发.')
    expect(input).toHaveValue('保留草稿')
    expect(screen.queryByRole('button', { name: '查看原始错误' })).toBeNull()
    await waitFor(() => expect(send).toBeDisabled())
    expect(apiClient.sendDouyinMessage).toHaveBeenCalledOnce()
  })
  it('invalidates an in-flight result and draft when the verified account changes', async () => {
    let resolve!: (result:ApiResult<DouyinMessageOutcome>) => void
    vi.mocked(apiClient.sendDouyinMessage).mockReturnValue(new Promise(done => { resolve = done }))
    const { input, send } = await mount()
    fireEvent.change(input,{ target:{ value:'旧账号草稿' } }); fireEvent.click(send)
    vi.mocked(apiClient.getDouyinSendState).mockResolvedValue({ ok:true, value:{ ...authenticated,uid:'98765',nickname:'新账号' } })
    fireEvent.click(screen.getByRole('button',{ name:'刷新账号' }))
    await screen.findByText('以 新账号 发送')
    expect(input).toHaveValue('')
    await act(async () => resolve({ ok:true, value:{ status:'accepted',message:'旧回执',nextAllowedAt:null } }))
    expect(screen.queryByText('旧回执')).toBeNull()
  })
})
