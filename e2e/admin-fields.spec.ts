/** Field switches retain assets and suppress processing, including dependent state groups. */
import { fileURLToPath } from 'node:url'
import { APP_ORIGIN, expect, test } from './electron'
import { chooseEditorVideo, failOnPageError, fixturesReady, invoke } from './helpers'

const official = fileURLToPath(new URL('../public/test-sources/official.mp4', import.meta.url))

test('关闭倒计时后保留样本, 禁用制作及自动步进, 重开后开关仍保留', async ({ page, electronApp }) => {
  test.skip(!fixturesReady(), '缺少测试源, 先运行 npm run fixtures')
  failOnPageError(page)
  await page.goto(APP_ORIGIN + '/admin')
  await chooseEditorVideo(electronApp, page, official)
  const video = page.locator('video.editor-media')
  await expect.poll(() => video.evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(2)
  for (const [index, value] of [0.42, 0.045, 0.16, 0.13].entries()) await page.locator('.roi-fields input').nth(index).fill(String(value))
  await video.evaluate((node: HTMLVideoElement) => { node.currentTime = 1 })
  await expect(page.locator('.glyph-box')).toHaveCount(4)
  for (const char of '0:19') await page.locator('.char-pad').getByRole('button', { name: char, exact: true }).click()
  await expect(page.locator('.template-thumb')).toHaveCount(4)
  const before = await invoke(page, 'editorProjectLoad', undefined)
  expect(before.ok).toBe(true)
  if (!before.ok || !before.value.project) throw new Error('Expected a saved editor project')
  const clock = before.value.project.pack.variants[0]!.fields.clock!
  const toggle = page.getByRole('switch', { name: /^启用当前字段/ })
  await toggle.press('Space')
  await expect(toggle).not.toBeChecked()
  await expect(page.getByRole('slider', { name: '阈值', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '自动 +1s', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '验证当前帧', exact: true })).toBeDisabled()
  await expect(page.locator('.verify-result')).toHaveText('字段已关闭')
  await expect(page.locator('.template-thumb')).toHaveCount(4)
  await expect(page.locator('.template-thumb').first()).toBeDisabled()
  await expect(page.getByRole('combobox', { name: '当前字段', exact: true }).locator('option:checked')).toHaveText('倒计时 (已关闭)')
  await page.getByRole('button', { name: '存为草稿', exact: true }).click()
  await expect(page.getByRole('status', { name: '编辑器提示' })).toContainText('已保存到本机草稿')
  const saved = await invoke(page, 'editorProjectLoad', undefined)
  expect(saved.ok && saved.value.project?.pack.variants[0]!.fields.clock).toEqual({ ...clock, enabled: false })
  await page.reload()
  await expect(toggle).not.toBeChecked()
  await expect(page.locator('.template-thumb')).toHaveCount(4)
  await expect.poll(() => video.evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(2)
  await video.evaluate((node: HTMLVideoElement) => { node.currentTime = 1 })
  await expect.poll(() => video.evaluate((node: HTMLVideoElement) => node.seeking)).toBe(false)
  await toggle.press('Space')
  await expect(toggle).toBeChecked()
  await expect(page.getByRole('slider', { name: '阈值', exact: true })).toBeEnabled()
  await expect(page.locator('.glyph-box')).toHaveCount(4)
  const enabled = await invoke(page, 'editorProjectLoad', undefined)
  expect(enabled.ok && enabled.value.project?.pack.variants[0]!.fields.clock).toEqual(clock)
})

test('关闭回放标记同时停用引用它的正反条件组, 模板和规则仍保留', async ({ page }, testInfo) => {
  failOnPageError(page)
  await page.goto(APP_ORIGIN + '/admin')
  const png = await page.evaluate(() => {
    const canvas = document.createElement('canvas')
    canvas.width = 320; canvas.height = 180
    const context = canvas.getContext('2d')!
    context.fillStyle = '#000'; context.fillRect(0, 0, 320, 180)
    context.fillStyle = '#fff'; context.fillRect(48, 26, 24, 28); context.fillRect(84, 26, 28, 8)
    return canvas.toDataURL('image/png').split(',')[1]!
  })
  await page.locator('main input[accept^="image/"]').setInputFiles({ name: 'replay.png', mimeType: 'image/png', buffer: Buffer.from(png, 'base64') })
  await expect(page.locator('img.editor-media')).toBeVisible()
  const target = page.getByRole('combobox', { name: '当前字段', exact: true })
  await target.selectOption('replay')
  for (const [index, value] of [40 / 320, 20 / 180, 120 / 320, 40 / 180].entries()) await page.locator('.roi-fields input').nth(index).fill(String(value))
  await page.getByRole('button', { name: '存为模板', exact: true }).click()
  await expect(page.locator('.cue-result')).toHaveText('出现 / 得分 1.000')
  await page.locator('.state-rules > summary').click()
  await page.getByRole('combobox', { name: '回放 1 回放标记', exact: true }).selectOption('present')
  await page.getByRole('combobox', { name: '暂停 1 回放标记', exact: true }).selectOption('absent')
  await expect.poll(async () => {
    const stored = await invoke(page, 'editorProjectLoad', undefined)
    return stored.ok ? stored.value.project?.pack.variants[0]!.states : null
  }).toEqual({ replay: [[{ kind: 'cue', cue: 'replay', present: true }]], paused: [[{ kind: 'cue', cue: 'replay', present: false }]] })
  const before = await invoke(page, 'editorProjectLoad', undefined)
  if (!before.ok || !before.value.project) throw new Error('Expected editor project')
  const original = before.value.project.pack.variants[0]!
  const toggle = page.getByRole('switch', { name: /^启用当前字段/ })
  await toggle.press('Space')
  await expect(page.locator('.cue-result')).toHaveText('已关闭')
  await expect(page.getByTestId('hud-content')).toHaveText('直播')
  await expect(page.getByTestId('hud-phase')).toHaveText('未配置')
  await expect(page.getByRole('button', { name: '存为模板', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '删除回放标记的模板', exact: true })).toHaveCount(1)
  await expect(page.getByRole('combobox', { name: '回放 1 回放标记 (已关闭)', exact: true })).toBeDisabled()
  await expect(page.getByRole('combobox', { name: '回放 1 回放标记 (已关闭)', exact: true })).toHaveValue('present')
  await expect(page.getByRole('combobox', { name: '暂停 1 回放标记 (已关闭)', exact: true })).toHaveValue('absent')
  await expect(page.getByText('该组引用了已关闭字段, 暂不参与判断', { exact: true })).toHaveCount(2)
  const disabled = await invoke(page, 'editorProjectLoad', undefined)
  if (!disabled.ok || !disabled.value.project) throw new Error('Expected disabled project')
  expect(disabled.value.project.pack.variants[0]!.cues.replay).toEqual({ ...original.cues.replay!, enabled: false })
  expect(disabled.value.project.pack.variants[0]!.states).toEqual(original.states)
  await page.screenshot({ path: testInfo.outputPath('disabled-replay-field.png'), fullPage: true })
  await toggle.press('Space')
  await expect(page.locator('.cue-result')).toHaveText('出现 / 得分 1.000')
  await expect(page.getByTestId('hud-content')).toHaveText('回放')
  await expect(page.getByRole('combobox', { name: '回放 1 回放标记', exact: true })).toBeEnabled()
})

test('关闭其他字段不影响当前开关, 关闭正在自动处理的倒计时会停止', async ({ page, electronApp }) => {
  test.skip(!fixturesReady(), '缺少测试源, 先运行 npm run fixtures')
  failOnPageError(page)
  await page.goto(APP_ORIGIN + '/admin')
  const target = page.getByRole('combobox', { name: '当前字段', exact: true })
  const toggle = page.getByRole('switch', { name: /^启用当前字段/ })
  await chooseEditorVideo(electronApp, page, official)
  const video = page.locator('video.editor-media')
  await expect.poll(() => video.evaluate((node: HTMLVideoElement) => node.readyState)).toBeGreaterThanOrEqual(2)
  for (const field of ['scoreLeft', 'scoreRight', 'replay', 'bomb', 'timeout', 'timeoutRight', 'roundPrefix', 'roundOver', 'roundHistory', 'scoreboard', 'organizer']) {
    await target.selectOption(field)
    await expect(toggle).toBeChecked()
    await toggle.press('Space')
    await expect(toggle).not.toBeChecked()
  }
  await target.selectOption('clock')
  await expect(toggle).toBeChecked()
  for (const [index, value] of [0.42, 0.045, 0.16, 0.13].entries()) await page.locator('.roi-fields input').nth(index).fill(String(value))
  await video.evaluate((node: HTMLVideoElement) => { node.currentTime = 1 })
  await expect(page.locator('.glyph-box')).toHaveCount(4)
  for (const char of '0:19') await page.locator('.char-pad').getByRole('button', { name: char, exact: true }).click()
  await video.evaluate((node: HTMLVideoElement) => {
    const descriptor = Object.getOwnPropertyDescriptor(HTMLMediaElement.prototype, 'currentTime')!
    Object.defineProperty(node, 'currentTime', { configurable: true, get() { return descriptor.get!.call(this) },
      set(value) { setTimeout(() => descriptor.set!.call(this, value), 1000) } })
  })
  await page.getByRole('button', { name: '自动 +1s', exact: true }).click()
  await expect(page.getByRole('button', { name: '停止自动 +1s', exact: true })).toBeVisible()
  await toggle.press('Space')
  await expect(page.getByRole('button', { name: '停止自动 +1s', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '自动 +1s', exact: true })).toBeDisabled()
  await page.waitForTimeout(1200)
  await expect(page.locator('.template-thumb')).toHaveCount(4)
})
