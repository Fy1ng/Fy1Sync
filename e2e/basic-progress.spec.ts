/** Real sidebar diagnostics, persistent manual regions and alignment interaction rules. */
import { expect, test } from './electron'
import { loadSource, openPlayer, revealOverlay, seekBoth, setPlaying, waitForBothReady } from './helpers'

async function load(page: import('@playwright/test').Page): Promise<void> {
  await loadSource(page, 'official', '/test-sources/auto-official.mp4')
  await loadSource(page, 'commentary', '/test-sources/auto-commentary.mp4')
  await page.keyboard.press('Escape')
  await waitForBothReady(page)
  await setPlaying(page, false)
  await seekBoth(page, 8, 8)
}

test.describe('侧栏基础识别', () => {
  test.setTimeout(120_000)

  test('显示实际二值图, 对齐中保留工具栏, 适配提示仅首次出现且成功提示简洁', async ({ page }) => {
    await openPlayer(page)
    await load(page)
    await expect(page.getByRole('region', { name: '基础识别', exact: true })).toBeVisible()
    await expect(page.getByRole('log', { name: '弹幕列表' })).toBeVisible()
    await setPlaying(page, true)
    await page.keyboard.press('a')
    const adapting = page.locator('.toast').filter({ hasText: '自动对齐适配中:' })
    await expect(adapting).toBeVisible()
    await expect(page.locator('.align-main.is-running')).toHaveCount(1)
    await page.mouse.move(4, 4)
    await page.waitForTimeout(3500)
    await expect(page.locator('main.theater')).toHaveAttribute('data-chrome', 'on')
    const binary = page.getByRole('article', { name: '官方画面基础识别' }).getByLabel('官方画面二值化结果')
    await expect(binary).toBeVisible()
    const pixels = await binary.evaluate((node: HTMLCanvasElement) => {
      const data = node.getContext('2d')!.getImageData(0, 0, node.width, node.height).data
      let white = 0, dark = 0
      for (let index = 0; index < data.length; index += 4) { if (data[index]! > 200) white++; if (data[index]! < 20) dark++ }
      return { width: node.width, height: node.height, white, dark }
    })
    expect(pixels.width).toBeGreaterThan(1)
    expect(pixels.height).toBeGreaterThan(1)
    expect(pixels.white).toBeGreaterThan(0)
    expect(pixels.dark).toBeGreaterThan(0)
    await expect(page.locator('.align-main.is-running')).toHaveCount(0, { timeout: 25_000 })
    await expect(page.locator('.toast').getByText('已自动对齐', { exact: true })).toBeVisible()
    await page.screenshot({ path: test.info().outputPath('basic-sidebar.png') })
    if (await adapting.isVisible()) await adapting.getByRole('button', { name: '关闭提示' }).click()
    await page.keyboard.press('a')
    await expect(page.locator('.align-main.is-running')).toHaveCount(1)
    await expect(adapting).toHaveCount(0)
    await expect(page.locator('.align-main.is-running')).toHaveCount(0, { timeout: 25_000 })
  })

  test('手动框选空白区域后不恢复自动定位, 重新载入后仍保留, 显式恢复后才重新找到倒计时', async ({ page }) => {
    await openPlayer(page)
    await load(page)
    const card = page.getByRole('article', { name: '官方画面基础识别' })
    await page.getByRole('button', { name: '框选倒计时', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: '倒计时范围 (两路共用)', exact: true })
    await expect(dialog.getByLabel('官方画面当前帧')).toHaveJSProperty('width', 1280)
    await dialog.getByRole('button', { name: '重新绘制', exact: true }).click()
    const stage = dialog.getByLabel('官方画面当前帧')
    const bounds = await stage.boundingBox()
    expect(bounds).not.toBeNull()
    await page.mouse.move(bounds!.x + bounds!.width * .05, bounds!.y + bounds!.height * .65)
    await page.mouse.down()
    await page.mouse.move(bounds!.x + bounds!.width * .20, bounds!.y + bounds!.height * .78, { steps: 5 })
    await page.mouse.up()
    await page.screenshot({ path: test.info().outputPath('manual-region.png') })
    await dialog.getByRole('button', { name: '使用此范围', exact: true }).click()
    await expect(dialog).toBeHidden()
    await expect(card).toContainText('手动范围')
    await setPlaying(page, true)
    await page.keyboard.press('a')
    await expect(page.locator('.align-main.is-running')).toHaveCount(1)
    await expect(page.locator('.align-main.is-running')).toHaveCount(0, { timeout: 25_000 })
    await expect(card).toContainText('手动范围未读出倒计时')
    await expect(card).not.toHaveAttribute('data-state', 'locked')
    await page.reload()
    await expect(page.locator('.studio')).toBeVisible()
    await page.keyboard.press('Escape')
    await load(page)
    await expect(card).toContainText('手动范围')
    await setPlaying(page, true)
    await page.keyboard.press('a')
    await expect(page.locator('.align-main.is-running')).toHaveCount(1)
    await expect(page.locator('.align-main.is-running')).toHaveCount(0, { timeout: 25_000 })
    await expect(card).not.toHaveAttribute('data-state', 'locked')
    await page.getByRole('button', { name: '自动重新寻找', exact: true }).click()
    await expect(card).toContainText('自动范围')
    await revealOverlay(page)
    await page.keyboard.press('a')
    await expect(page.locator('.align-main.is-running')).toHaveCount(1)
    await expect(page.locator('.align-main.is-running')).toHaveCount(0, { timeout: 25_000 })
    await expect(card).toHaveAttribute('data-state', 'locked')
    await expect(page.locator('.toast').getByText('已自动对齐', { exact: true })).toBeVisible()
  })
})
